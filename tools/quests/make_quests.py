def quest_uuid(key):
    return uuid.uuid5(NAMESPACE, "becom:quest:" + key)


def line_uuid():
    return uuid.uuid5(NAMESPACE, "becom:questline")


def high_low(u):
    # BetterQuesting stores a UUID as two signed 64-bit halves.
    high, low = struct.unpack(">qq", u.bytes)
    return high, low


def encode(u):
    return base64.urlsafe_b64encode(u.bytes).decode()


def key_part(u):
    # BetterQuesting's translation keys use the URL-safe base64 UUID without its padding.
    return encode(u).replace("=", "")


def file_stem(name, u):
    clean = re.sub(r"[^A-Za-z0-9]", "", name)[:16]
    return f"{clean}-{encode(u)}"


def item(id_, damage, count):
    return {"Count:3": count, "Damage:2": damage, "OreDict:8": "", "id:8": id_}


def quest_json(q, index):
    u = quest_uuid(q["key"])
    high, low = high_low(u)
    tier = TIER[q["tier"]]
    pre = {}
    for i, key in enumerate(q["pre"]):
        ph, pl = high_low(quest_uuid(key))
        pre[f"{i}:10"] = {"questIDHigh:4": ph, "questIDLow:4": pl}
    tasks = {}
    for i, task in enumerate(q["tasks"]):
        if task[0] == "item":
            _, id_, damage, count = task
            tasks[f"{i}:10"] = {
                "autoConsume:1": 0,
                "consume:1": 0,
                "groupDetect:1": 0,
                "ignoreNBT:1": 1,
                "index:3": i,
                "partialMatch:1": 1,
                "requireOnlyOneItem:1": 0,
                "requiredItems:9": {"0:10": item(id_, damage, count)},
                "taskID:8": "bq_standard:retrieval",
            }
        else:
            tasks[f"{i}:10"] = {"becomTask:8": task[1], "index:3": i, "taskID:8": "becom:event"}
    rewards = {
        "0:10": {
            "ignoreDisabled:1": 0,
            "index:3": 0,
            "rewardID:8": "bq_standard:item",
            "rewards:9": {"0:10": item(LOOTBAG, tier["bag"], 1)},
        }
    }
    if q["big"]:
        rewards["1:10"] = {
            "ignoreDisabled:1": 0,
            "index:3": 1,
            "rewardID:8": "bq_standard:item",
            "rewards:9": {"0:10": item(tier["coin"], 0, tier["coins"])},
        }
    icon_id, icon_damage = q["icon"]
    properties = {
        "autoClaim:1": 0,
        "desc:8": q["desc"],
        "globalShare:1": 1,
        "icon:10": item(icon_id, icon_damage, 1),
        "isGlobal:1": 0,
        "isMain:1": 1 if q["big"] else 0,
        "isSilent:1": 0,
        "lockedProgress:1": 0,
        "name:8": q["name"],
        "partySingleReward:1": 0,
        "questLogic:8": "AND",
        "repeatTime:3": -1,
        "repeat_relative:1": 1,
        "simultaneous:1": 0,
        "snd_complete:8": "random.levelup",
        "snd_update:8": "random.levelup",
        "taskLogic:8": "AND",
        "visibility:8": "NORMAL",
    }
    data = {
        "properties:10": {"betterquesting:10": properties},
        "questIDHigh:4": high,
        "questIDLow:4": low,
        "rewards:9": rewards,
        "tasks:9": tasks,
    }
    if pre:
        data["preRequisites:9"] = pre
    return u, data


def write_json(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, indent=2, sort_keys=True, ensure_ascii=True)
        f.write("\n")


def main():
    shutil.rmtree(os.path.join(ROOT, "DefaultQuests"), ignore_errors=True)
    lu = line_uuid()
    lhigh, llow = high_low(lu)
    line_dir_name = file_stem(LINE["name"], lu)
    line_dir = os.path.join(ROOT, "DefaultQuests", "QuestLines", line_dir_name)
    quest_dir = os.path.join(ROOT, "DefaultQuests", "Quests", line_dir_name)
    paths = []

    line = {
        "properties:10": {
            "betterquesting:10": {
                "bg_image:8": "",
                "bg_size:3": 256,
                "desc:8": LINE["desc"],
                "icon:10": item(LINE["icon"][0], LINE["icon"][1], 1),
                "name:8": LINE["name"],
                "visibility:8": "UNLOCKED",
            }
        },
        "questLineIDHigh:4": lhigh,
        "questLineIDLow:4": llow,
    }
    write_json(os.path.join(line_dir, "QuestLine.json"), line)
    paths.append(f"DefaultQuests/QuestLines/{line_dir_name}/QuestLine.json")

    lang = [LANG_BEGIN]
    lang.append(f"betterquesting.questline.{key_part(lu)}.name={LINE['name']}")
    lang.append(f"betterquesting.questline.{key_part(lu)}.desc={LINE['desc']}")
    for i, q in enumerate(QUESTS):
        u, data = quest_json(q, i)
        high, low = high_low(u)
        stem = file_stem(q["name"], u)
        x, y = q["pos"]
        write_json(
            os.path.join(line_dir, stem + ".json"),
            {"questIDHigh:4": high, "questIDLow:4": low, "sizeX:3": 24, "sizeY:3": 24, "x:3": x, "y:3": y},
        )
        paths.append(f"DefaultQuests/QuestLines/{line_dir_name}/{stem}.json")
        write_json(os.path.join(quest_dir, stem + ".json"), data)
        paths.append(f"DefaultQuests/Quests/{line_dir_name}/{stem}.json")
        lang.append(f"betterquesting.quest.{key_part(u)}.name={q['name']}")
        lang.append(f"betterquesting.quest.{key_part(u)}.desc={q['desc']}")
    lang.append(LANG_END)

    # Pack makers append this line to their own QuestLinesOrder.txt.
    with open(os.path.join(ROOT, "DefaultQuests", "QuestLinesOrder.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write(f"{encode(lu)}: {LINE['name']}\n")
    with open(os.path.join(ROOT, "index.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(paths) + "\n")

    with open(LANG, encoding="utf-8") as f:
        text = f.read()
    block = "\n".join(lang)
    if LANG_BEGIN in text:
        text = re.sub(re.escape(LANG_BEGIN) + r".*?" + re.escape(LANG_END), lambda m: block, text, flags=re.S)
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    with open(LANG, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"Wrote {len(QUESTS)} quests in line {encode(lu)}")


if __name__ == "__main__":
    main()
