package com.enn3developer.becom;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assertions.fail;

import java.util.Map;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;

import cpw.mods.fml.common.MetadataCollection;
import cpw.mods.fml.common.Mod;
import cpw.mods.fml.common.ModMetadata;
import cpw.mods.fml.common.versioning.ArtifactVersion;
import cpw.mods.fml.common.versioning.DefaultArtifactVersion;
import cpw.mods.fml.common.versioning.VersionParser;

/**
 * BeCom builds against GTNH Voice 0.11.0, and an older one fails on a missing API after loading. FML
 * checks the version only if the dependency names one, written as GTNH Voice writes its own, with the "v".
 */
class GtnhVoiceVersionTest {

    /** BeCom's GTNH Voice requirement, parsed the way FML's loader parses it. */
    private static ArtifactVersion required() {
        for (String dependency : BeCom.class.getAnnotation(Mod.class)
            .dependencies()
            .split(";")) {
            String[] parts = dependency.trim()
                .split(":");
            if (parts[0].equals("required-after") && parts[1].startsWith("gtnhvoice"))
                return VersionParser.parseVersionReference(parts[1]);
        }
        return fail("BeCom doesn't require GTNH Voice");
    }

    @ParameterizedTest
    @ValueSource(strings = { "v0.11.0", "v0.11.1", "v0.12.0", "v1.0.0" })
    void loadsWithGtnhVoice(String version) {
        assertTrue(
            required().containsVersion(new DefaultArtifactVersion("gtnhvoice", version)),
            "loads with " + version);
    }

    @ParameterizedTest
    @ValueSource(strings = { "v0.9.2", "v0.10.0", "v0.10.1" })
    void refusesAnOlderGtnhVoice(String version) {
        assertFalse(required().containsVersion(new DefaultArtifactVersion("gtnhvoice", version)), "refuses " + version);
    }

    /**
     * FML reads the dependencies from @Mod only when mcmod.info doesn't claim them with useDependencyInformation: a mod
     * that doesn't set useMetadata otherwise gets mcmod.info's lists, which held no versions at all.
     */
    @Test
    void forgeReadsTheRequirementFromTheModAnnotation() {
        ModMetadata metadata = MetadataCollection.from(BeCom.class.getResourceAsStream("/mcmod.info"), "mcmod.info")
            .getMetadataForId(BeCom.MODID, Map.of());
        assertFalse(metadata.autogenerated, "mcmod.info describes BeCom");
        assertFalse(metadata.useDependencyInformation, "mcmod.info's dependencies would stand in for @Mod's");
    }
}
